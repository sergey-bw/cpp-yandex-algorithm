/**
 * Спринт 7. Финальное задание: Одинаковые суммы
 *
 * Постановка задачи:
 *     Имеется набор положительных целых чисел. Требуется определить, можно ли
 *     разбить все числа на две группы так, чтобы сумма чисел в первой группе
 *     была в точности равна сумме чисел во второй группе.
 *     Каждое число из исходного набора должно попасть строго в одну из двух групп.
 * 
 *     Если разбить числа на две равные части возможно, программа выводит True,
 *     в противном случае — False.
 * 
 * Формат ввода:
 *     - В первой строке записано число n — количество элементов в наборе.
 *     - Во второй строке через пробел записаны n натуральных чисел.
 *
 * Ограничения:
 *     - Количество элементов n: 0 <= n <= 300
 *     - Значение каждого элемента: 0 <= item <= 300
 *     - Максимальная сумма всех элементов не превосходит 300 * 300 = 90 000
 *
 * Принцип работы:
 *     Если в множестве элементов есть такое подмножество, сумма элементов которого
 *     дает половину суммы целого множества, то остальные элементы множества так же
 *     дадут половину суммы.
 * 
 *     Отсюда следуют два базовых правила:
 *         1. Если общая сумма чисел нечётная, то разбить её на две равные целочисленные
 *            группы невозможно — сразу возвращаем False.
 *         2. Если сумма чётная, задача сводится к классической «задаче о рюкзаке»:
 *            нужно проверить, можно ли набрать точный вес half_sum из имеющихся предметов.
 * 
 *     Алгоритм решения:
 *         - Заводится массив достижимых сумм std::vector<bool> dp размера half_sum + 1,
 *           где dp[s] означает, можно ли набрать сумму s.
 *         - Базовый случай: dp[0] = true (нулевую сумму всегда можно набрать
 *           пустым набором чисел).
 *         - Для каждого числа перебираем возможные суммы в обратном порядке (справа налево,
 *           от half_sum вниз до значения текущего элемента массива). Обратный порядок
 *           гарантирует, что каждое число из набора будет использовано не более одного раза.
 *         - В качестве оптимизации добавлен ранний выход.
 *
 * Сложность:
 *     Временная:
 *         Подсчёт суммы входного массива: O(N), где
 *             N - количество элементов во входном массиве
 *         Заполнение таблицы динамики: O(N * S), где
 *             S - целевая сумма (половина от общей суммы всех элементов, не более 45 000)
 *         Общая временная сложность: O(N * S).
 *         На реальных тестах алгоритм работает быстрее за счёт раннего выхода при нахождении ответа.
 *
 *     Пространственная:
 *         Хранение входных данных: O(N)
 *         Массив флагов достижимых сумм dp: O(S), где
 *             S - половина общей суммы (до 45 001 бит, выровнено по машинному слову)
 *         Общая пространственная сложность: O(N + S)
 *
 * Ссылки на контест:
 *     Условие: https://contest.yandex.ru/contest/25597/problems/B/
 *     Посылка 2025: https://contest.yandex.ru/contest/25597/run-report/135060075/
 *     Посылка 2026: https://contest.yandex.ru/contest/25597/run-report/170976504/
 */

#include <iostream>
#include <vector>
#include <numeric>

bool HasEqualSumPartition(const std::vector<int>& numbers) {
    int sum = std::accumulate(numbers.begin(), numbers.end(), 0);
    if (numbers.size() < 2 || sum % 2 != 0) {
        return false;
    }

    std::vector<bool> dp(sum / 2 + 1, false);
    dp[0] = true;

    for (const int item : numbers) {
        if (item == 0) {
            continue;
        }

        for (int i = dp.size() - 1; i >= item; --i) {
            dp[i] = dp[i] || dp[i - item];
        }
        
        if (dp.back()) {
            break;
        }
    }
    return dp.back();
}

std::vector<int> ReadVector(std::istream& in) {
    int n = 0;
    in >> n;
    std::vector<int> numbers(n);
    for (int& item : numbers) {
        in >> item;
    }
    return numbers;
}

int main() {
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(nullptr);

    if (HasEqualSumPartition(ReadVector(std::cin))) {
        std::cout << "True";
    } else {
        std::cout << "False";
    }
    std::cout << '\n';
    return 0;
}