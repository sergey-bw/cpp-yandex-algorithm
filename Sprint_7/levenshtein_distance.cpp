/**
 * Спринт 7. Финальное задание: Расстояние по Левенштейну
 *
 * Постановка задачи:
 *     Расстоянием Левенштейна между двумя строками s и t называется количество атомарных
 *     изменений, с помощью которых можно одну строку превратить в другую. Под атомарными
 *     изменениями подразумеваются: удаление одного символа, вставка одного символа,
 *     замена одного символа на другой.
 * 
 *     Требуется найти и вывести расстояние Левенштейна для предложенной пары строк.
 * 
 * Формат ввода:
 *     - В первой строке записана строка s.
 *     - Во второй строке записана строка t.
 *
 * Ограничения:
 *     - Длины строк s и t не превосходят 1000 символов.
 *     - Строки состоят исключительно из строчных букв латинского алфавита
 *
 * Принцип работы:
 *     Для решения задачи используется алгоритм двумерного динамического программирования.
 * 
 *     Пусть dp[i][j] — минимальное расстояние между префиксом s[0..i-1] и префиксом t[0..j-1].
 * 
 *     Базовые случаи:
 *         - Преобразование префикса длины i в пустую строку требует i удалений: dp[i][0] = i.
 *         - Преобразование пустой строки в префикс длины j требует j вставок: dp[0][j] = j.
 * 
 *     Переход динамики:
 *         - Если символы совпадают (s[i-1] == t[j-1]), дополнительная операция не нужна:
 *             dp[i][j] = dp[i-1][j-1].
 *         - Если символы различны, выбирается минимум из трёх операций + 1:
 *             dp[i][j] = min ({
 *                 dp[i-1][j] + 1,   // Удаление символа из строки s
 *                 dp[i][j-1] + 1,   // Вставка символа в строку s (соответствует символу из t[j-1])
 *                 dp[i-1][j-1] + 1  // Замена символа s[i-1] на t[j-1]
 *             }).
 * 
 *     Оптимизация памяти:
 *         Для расчёта значений текущей строки матрицы dp требуются только значения
 *         предыдущей строки (i - 1). Вместо хранения полной матрицы используются два линейных
 *         буфера размера длины одной из строк, циклически чередующиеся.
 *
 * Сложность:
 *     Временная:
 *         O(N * M), где
 *             N - длина первой строки s
 *             M - длина второй строки t
 *         На каждой итерации выполняется O(1) операций
 *
 *     Пространственная:
 *         Хранение исходных строк: O(N + M)
 *         O(M) - дополнительная память для хранения массива dp
 *         Общая пространственная сложность: O(N + M)
 *
 * Ссылки на контест:
 *     Условие: https://contest.yandex.ru/contest/25597/problems/A/
 *     Посылка 2025: https://contest.yandex.ru/contest/25597/run-report/135051344/
 *     Посылка 2026: https://contest.yandex.ru/contest/25597/run-report/171076376/
 */

#include <iostream>
#include <algorithm>
#include <vector>
#include <string>
#include <numeric>

int LevenshteinDist(const std::string& str_a, const std::string& str_b) {
    if (str_a.empty() || str_b.empty()) {
        return std::max(str_a.length(), str_b.length());
    }

    const size_t n = str_a.length();
    const size_t m = str_b.length();

    std::vector<int> dp_prev_row(m + 1);
    std::vector<int> dp_curr_row(m + 1);
    std::iota(dp_curr_row.begin(), dp_curr_row.end(), 0);

    for (size_t i = 1; i <= n; ++i) {
        std::swap(dp_prev_row, dp_curr_row);
        dp_curr_row[0] = static_cast<int>(i);
        for (size_t j = 1; j <= m; ++j) {
            if (str_a[i - 1] == str_b[j - 1]) {
                dp_curr_row[j] = dp_prev_row[j - 1];
            } else {
                dp_curr_row[j] = 1 + std::min({
                    dp_prev_row[j],      // Удалить символ
                    dp_curr_row[j - 1],  // Вставить символ
                    dp_prev_row[j - 1],  // Заменить символ
                });
            }
        }
    }
    return dp_curr_row.back();
}

int main() {
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(nullptr);
    
    std::string str_a, str_b;
    std::getline(std::cin, str_a);
    std::getline(std::cin, str_b);
    std::cout << LevenshteinDist(str_a, str_b) << '\n';
    return 0;
}