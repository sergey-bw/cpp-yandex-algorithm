/**
 * Спринт 8. Финальное задание: B. Шпаргалка
 *
 * Постановка задачи:
 *     Дана строка текста (шпаргалка без пробелов) и словарь из N допустимых слов.
 *     Требуется определить, можно ли разбить исходный текст на слова из словаря.
 *     Каждое слово из словаря может использоваться произвольное количество раз.
 * 
 * Формат ввода:
 *     - В первой строке записан исходный текст s, состоящий из маленьких латинских букв.
 *     - Во второй строке записано целое число k — количество слов в словаре.
 *     - В следующих k строках записаны слова из словаря по одному в строке.
 *
 * Формат вывода:
 *     - Выведите "Yes", если текст можно разбить на слова из словаря, или "No" в противном случае.
 *
 * Ограничения:
 *     - Длина текста S не превосходит 100100 символов 
 *     - Количество слов в словаре k: 1 ≤ k ≤ 10000.
 *     - Длина каждого слова не превосходит 100 символов.
 *     - Все строки состоят исключительно из строчных букв латинского алфавита.
 *
 * Принцип работы (Префиксное дерево Trie + Динамическое программирование):
 *     1. Словарь упаковывается в префиксное дерево (Trie / бор).
 *     2. Выбор структуры для перехода по рёбрам:
 *        - По условию алфавит фиксирован: 26 строчных латинских букв ('a'..'z').
 *        - std::unordered_map имеет оверхед на корзины, динамические аллокации узлов
 *          и вычисление хеш-функции.
 *        - Массив фиксированного размера std::array<Node*, 26> даёт строгий O(1) доступ
 *          по индексу (c - 'a') и высокую кэш-локальность.
 *        - Профилирование показало:
 *              Контейнер       Время (мс)   Память (МБ)
 *              -----------------------------------------
 *              Хеш-таблица     10           3.25
 *              Массив          7            3.28
 *          Массив выигрывает по скорости ~30% при сопоставимом потреблении памяти.
 *     3. Проверка разбиения (ДП):
 *        - Заводится булев массив dp размера |s| + 1, где dp[i] означает,
 *          можно ли составить префикс текста длины i словами из словаря.
 *        - Базовый случай: dp[0] = true (пустой префикс всегда валиден).
 *        - Если dp[i] == true, спускаемся по бору начиная с символа text[i],
 *          пока есть соответствующие рёбра.
 *        - Если в процессе спуска встречаем терминальный узел (слово закончилось на позиции j),
 *          помечаем dp[j] = true.
 *        - При нахождении dp[|s|] == true срабатывает ранняя остановка.
 *
 * Сложность:
 *     Временная:
 *         - Построение бора: O(L), где L — суммарная длина всех слов словаря.
 *         - Проверка текста: O(|s| * M), где M — максимальная длина слова в словаре (M <= 100).
 *           Поскольку глубина спуска по бору ограничена высотой дерева M,
 *           внутренний цикл делает не более M шагов для каждого достижимого индекса i.
 *         - Общая временная сложность: O(L + |s| * M). В худшем случае (если M сопоставимо с |s|)
 *           сложность составляет O(L + |s|^2).
 *
 *     Пространственная:
 *         - Префиксное дерево: O(V * |Sigma|), где V — число вершин в боре (V <= L),
 *           а |Sigma| = 26 — размер алфавита.
 *         - Массив динамики dp: O(|s|).
 *         - Общая пространственная сложность: O(L * |Sigma| + |s|).
 *
 * Ссылки на контест:
 *     Условие: https://contest.yandex.ru/contest/26133/problems/B/
 *     Посылка 2025: https://contest.yandex.ru/contest/26133/run-report/135531823/
 *     Посылка 2026: 
 */

#include <iostream>
#include <vector>
#include <string>
#include <array>
#include <deque>

class Trie {
public:
    Trie(): nodes(1, Node{}) , root(&nodes[0]) {}

    Trie(const std::vector<std::string>& words)
        : Trie()
    {
        for (const auto& word : words) {
            InsertWord(word);
        }
    }

    void InsertWord(const std::string& word) {
        Node* curr_node = root;
        for (char c : word) {
            Node*& child_node = curr_node->children[c - 'a'];
            if(child_node == nullptr) {
                nodes.emplace_back();
                child_node = &nodes.back();
            }
            curr_node = child_node;
        }
        curr_node->is_teminal = true;
    }

    bool IsSplitTextIntoWords(const std::string& text) const noexcept{
        std::vector<bool> dp(text.length() + 1, false);
        dp[0] = true;
        for (size_t i = 1; i < dp.size() && !dp.back(); ++i) {
            const Node* curr_node = root;
            if (dp[i - 1]) {
                for (size_t j = i; j < dp.size(); ++j) {
                    curr_node = curr_node->children[text[j - 1] - 'a'];
                    if (curr_node == nullptr) {
                        break;
                    }
                    dp[j] = dp[j] || curr_node->is_teminal;
                }
            }
        }
        return dp.back();
    }

private:
    struct Node {
        std::array<Node*, 26> children;
        bool is_teminal = false;

        Node() {
            children.fill(nullptr);
        }
    };
    std::deque<Node> nodes;
    Node* root;
};

std::vector<std::string> ReadWords(std::istream& in) {
    int n;
    in >> n;
    std::vector<std::string> words(n);
    for (auto& word : words) {
        in >> word;
    }
    return words;
}

int main() {
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(nullptr);

    std::string line;
    std::cin >> line;

    if (Trie{ReadWords(std::cin)}.IsSplitTextIntoWords(line)) {
        std::cout << "Yes";
    } else {
        std::cout << "No";
    }
    std::cout << '\n';
    return 0;
}