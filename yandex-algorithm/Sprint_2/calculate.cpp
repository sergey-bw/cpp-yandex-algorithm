/**
 * Спринт 2. Финальное задание: Калькулятор (Обратная польская нотация)
 *
 * Постановка задачи:
 *     Задано выражение в обратной польской нотации, состоящее из целых чисел
 *     и знаков бинарных операций: '+', '-', '*', '/'.
 * 
 *     В обратной польской нотации операнды расположены перед знаками операций.
 *     Например: 10 2 4 * - означает 10 - 2 * 4 и равно 2.
 *     Знак * стоит сразу после чисел 2 и 4, значит к ним нужно применить операцию,
 *     то есть перемножить эти два числа. В результате получим 8.
 *     После этого выражение приобретёт вид: 10 8 -.
 * 
 *     Требуется вычислить результат выражения.
 * 
 * Формат ввода:
 *     В единственной строке дано выражение, записанное в обратной польской нотации.
 *     Числа и арифметические операции записаны через пробел.
 *     На вход могут подаваться операции: +, -, *, / и числа, по модулю не превосходящие 10000.
 * 
 * Формат вывода:
 *     Выведите единственное число - значение выражения.
 *     
 * Ограничения:
 *     Гарантируется, что значение промежуточных выражений в тестовых данных по модулю не больше 50000.
 *     Под делением понимается математическое целочисленное деление. Это значит, что округление
 *     всегда происходит вниз. А именно: если a / b = c, то b * c - это наибольшее число, которое
 *     не превосходит a и одновременно делится без остатка на b.
 *     Гарантируется, что деления на отрицательное число нет.
 *
 * Принцип работы:
 *     Используется стек операндов.
 *     - При чтении очередного числа помещаем его в стек.
 *     - При встрече оператора извлекаем сначала правый, затем левый операнд.
 *       Выполняем операцию и помещаем результат обратно в стек.
 *     После обработки выражения в стеке остаётся единственное число - ответ.
 * 
 * Сложность:
 *     Временная:
 *         Чтение строки и обработка всех её символов: O(N), где
 *             N - длина входной строки
 * 
 *     Пространственная:
 *         Хранение входной строки, её копии в потоке и стека операндов: O(N)
 *
 * Ссылки на контест:
 *     Условие: https://contest.yandex.ru/contest/22781/problems/B/
 *     Посылка 2024: https://contest.yandex.ru/contest/22781/run-report/126860559/
 *     Посылка 2026: https://contest.yandex.ru/contest/22781/run-report/171951391/
 */

#include <cassert>
#include <cctype>
#include <iostream>
#include <sstream>
#include <stack>
#include <string>
#include <vector>

int ExecuteOperation(char op, int lhs, int rhs) {
    switch (op) {
        case '+':
            return lhs + rhs;
        case '-':
            return lhs - rhs;
        case '*':
            return lhs * rhs;
        case '/': {
            // rhs > 0 по условию задачи.
            // При делении отрицательного числа с остатком округляем вниз (floor).
            int res = lhs / rhs;
            int rem = lhs % rhs;
            return (lhs < 0 && rem != 0) ? (res - 1) : res;
        }
        default:
            assert(false && "Unknown operator");
            return 0;
    }
}

int Calculation(const std::string& line) {
    std::istringstream stream(line);
    std::stack<int, std::vector<int>> operands;
    std::string token;

    while (stream >> token) {
        if (std::isdigit(static_cast<unsigned char>(token.back()))) {
            operands.push(std::stoi(token));
        } else {
            int rhs = operands.top();
            operands.pop();
            int lhs = operands.top();
            operands.pop();
            operands.push(ExecuteOperation(token[0], lhs, rhs));
        }
    }
    return operands.top();
}

int main() {
    std::ios_base::sync_with_stdio(false);
    std::cin.tie(nullptr);

    std::string line;
    if (std::getline(std::cin, line)) {
        std::cout << Calculation(line) << "\n";
    }

    return 0;
}